"""Write the synthetic dataset to disk.

    python -m ml.data_generation.generate_dataset --seed 42 --days 200 --out ml/datasets

Produces `synthetic_visits.csv.gz` (every row has is_synthetic=True) and `dataset_meta.json` with
the seed, generator version, row count and a SHA-256 of the CSV content. The gzip stream stores no
timestamp, so the same seed always yields byte-identical files.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import io
import json
from pathlib import Path

from ml.data_generation.simulator import GENERATOR_VERSION, generate
from ml.preprocessing.features import FEATURE_COLUMNS, TARGET

COLUMNS = ("day_index", "doctor_id", *FEATURE_COLUMNS, TARGET, "is_synthetic")


def to_csv_bytes(rows: list[dict]) -> bytes:
    buffer = io.StringIO(newline="")
    writer = csv.DictWriter(buffer, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow({k: (repr(row[k]) if isinstance(row[k], float) else row[k]) for k in COLUMNS})
    return buffer.getvalue().encode()


def write_dataset(out_dir: Path, seed: int, days: int, doctors: int) -> dict:
    rows = generate(seed=seed, n_doctors=doctors, n_days=days)
    content = to_csv_bytes(rows)
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "synthetic_visits.csv.gz").open("wb") as raw, \
            gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as gz:
        gz.write(content)
    meta = {
        "synthetic": True,
        "note": "Generated by a queueing simulation. Contains no real patient data.",
        "generator_version": GENERATOR_VERSION, "seed": seed, "days": days, "doctors": doctors,
        "rows": len(rows), "columns": list(COLUMNS), "sha256": hashlib.sha256(content).hexdigest(),
    }
    (out_dir / "dataset_meta.json").write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n")
    return meta


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--days", type=int, default=200)
    parser.add_argument("--doctors", type=int, default=12)
    parser.add_argument("--out", type=Path, default=Path("ml/datasets"))
    args = parser.parse_args()
    meta = write_dataset(args.out, args.seed, args.days, args.doctors)
    print(f"wrote {meta['rows']} synthetic rows to {args.out} (sha256 {meta['sha256'][:12]}...)")


if __name__ == "__main__":
    main()
